"""Builds the resume example and resume template pages (and their two hub pages) from seo_resume.py."""
import html, json, os, re
import seo_resume as SR

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
E = html.escape


def themes():
    """Read the 25 design definitions from resume-themes.js so pages always match the builder."""
    src = open(os.path.join(ROOT, 'assets', 'js', 'tools', 'resume-themes.js'), encoding='utf-8').read()
    out = []
    for line in src.splitlines():
        m = re.match(r"\s*\{ id: '(\w+)', name: '([^']+)', tag: '(\w+)'(.*)\},?\s*$", line)
        if not m: continue
        rest = m.group(4)
        best = re.search(r'best: \[([^\]]*)\]', rest)
        out.append(dict(id=m.group(1), name=m.group(2), tag=m.group(3), photo='photo: true' in rest,
                        best=[b.strip().strip('"\'') for b in best.group(1).split(',')] if best else []))
    return out


def write_samples_js():
    js = ('/* Generated by build/build.py from build/seo_resume.py - do not edit by hand */\n'
          'window.SK_SAMPLES = %s;\nwindow.SK_SAMPLE_LABELS = %s;\n') % (
        json.dumps(SR.SAMPLES, ensure_ascii=False), json.dumps(SR.LABELS, ensure_ascii=False))
    open(os.path.join(ROOT, 'assets', 'js', 'tools', 'resume-samples.js'), 'w', encoding='utf-8').write(js)


def design_card(t, href, img=None, alt=None, label='Use this design'):
    tag = ('Job-portal friendly' if t['tag'] == 'ats' else 'Stylish') + (' · photo' if t['photo'] else '')
    best = ', '.join(t['best'][:3])
    return ('<article class="show-card"><a class="show-img" href="%(h)s"><img src="%(img)s" width="600" height="849" loading="lazy" alt="%(alt)s"></a>'
            '<div class="show-info"><b>%(n)s</b>%(best)s<span class="tpl-tag %(tg)s">%(tag)s</span></div>'
            '<a class="btn btn-small show-use" href="%(h)s">%(lbl)s</a></article>') % dict(
        h=href, img=img or '{{R}}assets/img/designs/%s.webp' % t['id'], alt=E(alt or '%s resume template preview' % t['name']), n=E(t['name']),
        best=('<span class="design-best">Best for: %s</span>' % E(best)) if best else '', tg=t['tag'], tag=tag, lbl=label)


def faq_block(faq):
    return '<section class="section"><h2>Questions people ask</h2><div class="faq">%s</div></section>' % ''.join(
        '<details><summary>%s</summary><p>%s</p></details>' % (E(q), a) for q, a in faq)


def promise():
    return ('<p class="promise"><span>{{ICON:check:18:#1D6B45}} Free</span><span>{{ICON:check:18:#1D6B45}} No watermark</span>'
            '<span>{{ICON:check:18:#1D6B45}} No sign-up</span><span>{{ICON:check:18:#1D6B45}} PDF download</span></p>')


def example_cards(exclude=None, limit=None):
    items = [x for x in SR.EXAMPLES if x['slug'] != exclude][:limit]
    return '<div class="show-grid">' + ''.join(
        '<article class="show-card"><a class="show-img" href="{{R}}resume-examples/%s/"><img src="{{R}}assets/img/examples/%s.webp" width="600" height="849" loading="lazy" alt="%s resume example"></a>'
        '<div class="show-info"><b>%s</b><span class="design-best">Resume example</span></div>'
        '<a class="btn btn-small btn-light show-use" href="{{R}}resume-examples/%s/">See example</a></article>' % (
            x['slug'], x['slug'], E(x['job']), E(x['job']), x['slug']) for x in items) + '</div>'


def template_links(exclude=None):
    return '<nav class="related" aria-label="Resume templates">' + ''.join(
        '<a href="{{R}}resume-templates/%s/">%s</a>' % (t['slug'], E(t['name'])) for t in SR.TEMPLATES if t['slug'] != exclude) + '</nav>'


